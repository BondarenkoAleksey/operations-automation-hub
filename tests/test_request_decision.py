from decimal import Decimal

import pytest

from operations_automation_hub.schemas.request import RequestStatus
from operations_automation_hub.services.request_decision import (
    DecisionReason,
    RequestDecision,
    ScoringStatus,
    decide_request,
)


@pytest.mark.parametrize(
    ("inn_is_valid", "risk_score", "scoring_status", "amount", "expected"),
    [
        (
            True,
            79,
            ScoringStatus.APPROVED,
            Decimal("100000.00"),
            RequestDecision(
                status=RequestStatus.APPROVED, reason=DecisionReason.AUTOMATIC_APPROVAL
            ),
        ),
        (
            True,
            80,
            ScoringStatus.APPROVED,
            Decimal("100000.00"),
            RequestDecision(
                status=RequestStatus.MANUAL_REVIEW,
                reason=DecisionReason.HIGH_RISK_SCORE,
            ),
        ),
        (
            True,
            81,
            ScoringStatus.APPROVED,
            Decimal("100000.00"),
            RequestDecision(
                status=RequestStatus.MANUAL_REVIEW,
                reason=DecisionReason.HIGH_RISK_SCORE,
            ),
        ),
        (
            False,
            0,
            ScoringStatus.APPROVED,
            Decimal("100000.00"),
            RequestDecision(
                status=RequestStatus.REJECTED,
                reason=DecisionReason.INVALID_INN,
            ),
        ),
        (
            False,
            95,
            ScoringStatus.APPROVED,
            Decimal("100000.00"),
            RequestDecision(
                status=RequestStatus.REJECTED,
                reason=DecisionReason.INVALID_INN,
            ),
        ),
        (
            True,
            79,
            ScoringStatus.DECLINED,
            Decimal("100000.00"),
            RequestDecision(
                status=RequestStatus.REJECTED,
                reason=DecisionReason.SCORING_DECLINED,
            ),
        ),
        (
            True,
            80,
            ScoringStatus.DECLINED,
            Decimal("100000.00"),
            RequestDecision(
                status=RequestStatus.MANUAL_REVIEW,
                reason=DecisionReason.HIGH_RISK_SCORE,
            ),
        ),
        (
            False,
            95,
            ScoringStatus.DECLINED,
            Decimal("100000.00"),
            RequestDecision(
                status=RequestStatus.REJECTED,
                reason=DecisionReason.INVALID_INN,
            ),
        ),
        (
            True,
            10,
            ScoringStatus.APPROVED,
            Decimal("499999.99"),
            RequestDecision(
                status=RequestStatus.APPROVED, reason=DecisionReason.AUTOMATIC_APPROVAL
            ),
        ),
        (
            True,
            10,
            ScoringStatus.APPROVED,
            Decimal("500000.00"),
            RequestDecision(
                status=RequestStatus.APPROVED, reason=DecisionReason.AUTOMATIC_APPROVAL
            ),
        ),
        (
            True,
            10,
            ScoringStatus.APPROVED,
            Decimal("500000.01"),
            RequestDecision(
                status=RequestStatus.MANUAL_REVIEW,
                reason=DecisionReason.HIGH_AMOUNT,
            ),
        ),
        (
            True,
            80,
            ScoringStatus.APPROVED,
            Decimal("700000.00"),
            RequestDecision(
                status=RequestStatus.MANUAL_REVIEW,
                reason=DecisionReason.HIGH_RISK_SCORE,
            ),
        ),
        (
            True,
            10,
            ScoringStatus.DECLINED,
            Decimal("700000.00"),
            RequestDecision(
                status=RequestStatus.REJECTED,
                reason=DecisionReason.SCORING_DECLINED,
            ),
        ),
        (
            False,
            10,
            ScoringStatus.APPROVED,
            Decimal("700000.00"),
            RequestDecision(
                status=RequestStatus.REJECTED,
                reason=DecisionReason.INVALID_INN,
            ),
        ),
    ],
)
def test_decide_request(inn_is_valid, risk_score, scoring_status, amount, expected):
    assert (
        decide_request(
            inn_is_valid=inn_is_valid,
            risk_score=risk_score,
            scoring_status=scoring_status,
            amount=amount,
        )
        == expected
    )
